-- ====================================================================
--  SUPABASE SCHEMA SETUP — AKV Admin Dashboard
--  Aman dijalankan ulang (idempoten) di Supabase SQL Editor.
-- ====================================================================

-- 1. Tabel contact (single row, id=1)
create table if not exists public.contact (
  id int primary key default 1 check (id = 1),
  whatsapp text not null default '',
  instagram text not null default '',
  tiktok text not null default '',
  email text not null default ''
);

-- 2. Tabel services (plus estimasi harga & durasi)
create table if not exists public.services (
  id int primary key generated by default as identity,
  icon text not null default 'sparkles',
  title text not null default '',
  "desc" text not null default '',
  price text not null default '',
  duration text not null default ''
);

alter table public.services add column if not exists price text not null default '';
alter table public.services add column if not exists duration text not null default '';

-- 3. Tabel portfolio_items (plus deskripsi untuk modal detail)
create table if not exists public.portfolio_items (
  id int primary key generated by default as identity,
  title text not null default '',
  category text not null default '',
  image text,
  tone text not null default 'from-akv-blue to-akv-royal',
  description text not null default ''
);

alter table public.portfolio_items add column if not exists description text not null default '';

-- 4. Tabel testimonials
create table if not exists public.testimonials (
  id int primary key generated by default as identity,
  name text not null default '',
  role text not null default '',
  quote text not null default ''
);

-- 5. Tabel team_members
create table if not exists public.team_members (
  id int primary key generated by default as identity,
  name text not null default '',
  role text not null default '',
  url text not null default ''
);

-- 6. Tabel pricing_packages (3 paket utama + editable di admin)
create table if not exists public.pricing_packages (
  id int primary key generated by default as identity,
  name text not null default '',
  badge text not null default '',
  price text not null default '',
  unit text not null default 'per proyek',
  "desc" text not null default '',
  featured boolean not null default false,
  cta_label text not null default 'Pilih Paket',
  features jsonb not null default '[]'::jsonb
);

-- 7. Tabel faqs (FAQ pembelian + editable di admin)
create table if not exists public.faqs (
  id int primary key generated by default as identity,
  question text not null default '',
  answer text not null default ''
);

-- ====================================================================
--  ROW LEVEL SECURITY (RLS)
--  - Public SELECT untuk semua tabel (landing page bisa baca)
--  - INSERT/UPDATE/DELETE hanya untuk authenticated users (admin)
